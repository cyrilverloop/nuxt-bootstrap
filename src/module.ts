import {
    addComponentsDir,
    addPlugin,
    addTypeTemplate,
    createResolver,
    defineNuxtModule,
    resolvePath
} from '@nuxt/kit';

// Module options TypeScript interface definition
export interface ModuleOptions {}

export default defineNuxtModule<ModuleOptions>({
    meta: {
        name: '@cyrilverloop/nuxt-bootstrap',
        configKey: 'nuxtBootstrap',
    },
    // Default configuration options of the Nuxt module
    defaults: {},
    async setup(_options, _nuxt) {
        _nuxt.options.css.push('bootstrap/dist/css/bootstrap.min.css');
        const resolver = createResolver(import.meta.url);

        // Do not add the extension since the `.ts` will be transpiled to `.mjs` after `npm run prepack`
        addPlugin(resolver.resolve('./runtime/plugins/useBootstrap.client'));

        addComponentsDir({
            path: resolver.resolve('./runtime/components/')
        });

        addTypeTemplate({
            filename: 'types/nuxt-bootstrap.d.ts',
            getContents: () => `// Generated by nuxt-bootstrap\n`
            + `import { type BSAccordionItem } from "` + resolver.resolve('./runtime/types/BSAccordionItem') + `";\n`
            + `import { type BSBadge } from "` + resolver.resolve('./runtime/types/BSBadge') + `";\n`
            + `import { type BSBreadcrumb } from "` + resolver.resolve('./runtime/types/BSBreadcrumb') + `";\n`
            + `import { type BSBreadcrumbs } from "` + resolver.resolve('./runtime/types/BSBreadcrumbs') + `";\n`
            + `import { type BSIconPageItem } from "` + resolver.resolve('./runtime/types/BSIconPageItem') + `";\n`
            + `import { type BSNavItem } from "` + resolver.resolve('./runtime/types/BSNavItem') + `";\n`
            + `import { type BSPageItem } from "` + resolver.resolve('./runtime/types/BSPageItem') + `";\n`
            + `import { type BSProgress } from "` + resolver.resolve('./runtime/types/BSProgress') + `";\n`
            + `import { BSAutoClose } from "` + resolver.resolve('./runtime/types/BSAutoClose') + `";\n`
            + `import { BSDropdownContent } from "` + resolver.resolve('./runtime/types/dropdown/BSDropdownContent') + `";\n`
            + `import { BSDropdownDirection } from "` + resolver.resolve('./runtime/types/dropdown/BSDropdownDirection') + `";\n`
            + `import { BSDropdownDivider } from "` + resolver.resolve('./runtime/types/dropdown/BSDropdownDivider') + `";\n`
            + `import { BSDropdownLink } from "` + resolver.resolve('./runtime/types/dropdown/BSDropdownLink') + `";\n`
            + `import { BSDropdownText } from "` + resolver.resolve('./runtime/types/dropdown/BSDropdownText') + `";\n`
            + `import { BSDropdownTitle } from "` + resolver.resolve('./runtime/types/dropdown/BSDropdownTitle') + `";\n`
            + `import { BSJustifyContent } from "` + resolver.resolve('./runtime/types/BSJustifyContent') + `";\n`
            + `import { BSSize } from "` + resolver.resolve('./runtime/types/BSSize') + `";\n`
            + `import { BSSpinnerType } from "` + resolver.resolve('./runtime/types/BSSpinnerType') + `";\n`
            + `import { BSVariant } from "` + resolver.resolve('./runtime/types/BSVariant') + `";\n`
            + `export {`
            + `type BSAccordionItem,`
            + `type BSBadge,`
            + `type BSBreadcrumb,`
            + `type BSBreadcrumbs,`
            + `type BSIconPageItem,`
            + `type BSNavItem,`
            + `type BSProgress,`
            + `type BSPageItem,`
            + `BSAutoClose,`
            + `BSDropdownContent,`
            + `BSDropdownDirection,`
            + `BSDropdownDivider,`
            + `BSDropdownLink,`
            + `BSDropdownText,`
            + `BSDropdownTitle,`
            + `BSJustifyContent,`
            + `BSSize,`
            + `BSSpinnerType,`
            + `BSVariant`
            + `};`,
        });

        _nuxt.options.alias['#nbs'] = await resolvePath("#build") + "/types/nuxt-bootstrap.d";
    }
});
